"""Combine several models' scores into one comparison table.

Reads results/metrics/<model>.jsonl (written by scripts/score.py) and writes
results/comparison.md: one table per group, metrics as rows, models as columns in the order
given. Each rate is shown as % (k/n) [95% CI, cluster bootstrap over contexts].

Usage:
  python scripts/compare.py                      # all models in results/metrics/
  python scripts/compare.py base lora_1h_1e-5    # chosen models, in this column order
  python scripts/compare.py base ctrl --out results/comparison_ctrl.md
"""

import argparse
from pathlib import Path

from report_lib import REPO, comparison_markdown, load_rows


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("models", nargs="*", help="Model names (default: all in results/metrics/).")
    p.add_argument("--out", type=Path, default=REPO / "results" / "comparison.md")
    args = p.parse_args()

    models = load_rows(args.models or None)
    if not models:
        raise SystemExit("No results found in results/metrics/.")
    md = ("# Model comparison\n\nGenerated by scripts/compare.py from results/metrics/ for: "
          + ", ".join(models) + ".\n\n" + comparison_markdown(models))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md)
    print(md)
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
