"""Data size x onset weighting (2x2 per learning rate) -> results/onset_x_size.md.

Cells: the best checkpoint (results/best/<run>.json) of train_{1h,10h}_v2_lr<LR>[_onsetw3], on the 400
eval v2 files at seed 1 (human files left out), as in scripts/paired_diff.py.
Per cell: overall behavior score (report_lib.SCORE_COMPONENTS: mean of silence = 100 - interrupt,
return = 100 - missed resume, answer = ordinary response, addressee = 100 - distractor response),
wait success, interrupt rate, missed resume, ordinary response, distractor response, each with a 95%
cluster-bootstrap CI.
Effects (all paired: the four models' counts come from the same resampled clusters in every draw):
onset effect at 1h and at 10h, data effect without and with onset, and the interaction
(10h onset - 10h plain) - (1h onset - 1h plain) for every metric.
Usage: python scripts/onset_x_size.py [--b 5000]
"""
import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paired_diff import counts, load  # noqa: E402  (same row selection and counting as paired_diff.py)
from report_lib import SCORE_COMPONENTS, cluster_of  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
LRS = ["1e-4", "3e-5"]
CELLS = [("1h", "plain", "train_1h_v2_lr{lr}"), ("1h", "onset", "train_1h_v2_lr{lr}_onsetw3"),
         ("10h", "plain", "train_10h_v2_lr{lr}"), ("10h", "onset", "train_10h_v2_lr{lr}_onsetw3")]
# (label, row key, kind, higher is better); score first
RATES = [("wait success", "wait_success", "run", True), ("interrupt", "interrupted", "run", False),
         ("missed resume", "missed_resume", "run", False), ("ordinary response", "ordinary_answered", "list", True),
         ("distractor response", "distractor_responses", "list", False)]


def best(run: str) -> str:
    return json.loads((REPO / f"results/best/{run}.json").read_text())["model"]


def arrays(rows, ids, cs, key, kind):
    k, n = counts(rows, ids, key, kind)
    return np.array([k[c] for c in cs], float), np.array([n[c] for c in cs], float)


def stats(models: dict, b: int, seed: int = 0) -> dict:
    """{metric: {cell: (point, draws)}}; metric values in % (score on 0-100)."""
    rows = {c: load(m) for c, m in models.items()}
    ids = sorted(set.intersection(*(set(r) for r in rows.values())))
    cs = sorted({cluster_of(next(iter(rows.values()))[i]) for i in ids})
    idx = np.random.default_rng(seed).integers(0, len(cs), size=(b, len(cs)))
    out = defaultdict(dict)
    for cell, r in rows.items():
        for label, key, kind, _ in RATES:
            K, N = arrays(r, ids, cs, key, kind)
            out[label][cell] = (100 * K.sum() / N.sum(), 100 * K[idx].sum(1) / np.maximum(N[idx].sum(1), 1))
        comp_pt, comp_dr = [], []
        for _, key, kind, inv in SCORE_COMPONENTS:
            K, N = arrays(r, ids, cs, key, kind)
            pt, dr = K.sum() / N.sum(), K[idx].sum(1) / np.maximum(N[idx].sum(1), 1)
            comp_pt.append(100 * (1 - pt if inv else pt)); comp_dr.append(100 * (1 - dr if inv else dr))
        out["overall score"][cell] = (float(np.mean(comp_pt)), np.mean(comp_dr, 0))
    return out, len(ids), len(cs)


def ci(d):
    lo, hi = np.percentile(d, [2.5, 97.5])
    return lo, hi


def main() -> None:
    p = argparse.ArgumentParser(); p.add_argument("--b", type=int, default=5000); args = p.parse_args()
    md = ["# Data size × onset weighting", "",
          "Generated by `scripts/onset_x_size.py`. Each cell is a run's best checkpoint (`results/best/`) on the 400 eval v2 "
          "files at seed 1. Rates in %, overall score 0–100 (mean of silence, return, answer, addressee). "
          "Brackets: 95% cluster-bootstrap CIs; effects are paired (the four models resampled on the same clusters in "
          f"each of {args.b} draws). * = the effect's CI excludes 0.", ""]
    metrics = ["overall score"] + [r[0] for r in RATES]
    for lr in LRS:
        models = {(s, w): best(t.format(lr=lr)) for s, w, t in CELLS}
        st, nf, nc = stats(models, args.b)
        md += [f"## lr {lr}", "", "Models: " + ", ".join(f"{s} {w} = `{m}`" for (s, w), m in models.items())
               + f" ({nf} paired files, {nc} clusters).", ""]
        for m in metrics:
            md += [f"**{m}**", "", "| | plain | onset ×3 | onset effect (onset − plain) |", "|---|---|---|---|"]
            for s in ("1h", "10h"):
                (pp, pd), (op, od) = st[m][(s, "plain")], st[m][(s, "onset")]
                lo, hi = ci(od - pd)
                eff = op - pp
                md.append(f"| {s} | {pp:.1f} [{ci(pd)[0]:.1f}–{ci(pd)[1]:.1f}] | {op:.1f} [{ci(od)[0]:.1f}–{ci(od)[1]:.1f}] | "
                          f"{eff:+.1f} [{lo:+.1f}, {hi:+.1f}]{'*' if not lo <= 0 <= hi else ''} |")
            rows = []
            for w in ("plain", "onset"):
                (ap, ad), (bp, bd) = st[m][("1h", w)], st[m][("10h", w)]
                lo, hi = ci(bd - ad)
                rows.append(f"{bp - ap:+.1f} [{lo:+.1f}, {hi:+.1f}]{'*' if not lo <= 0 <= hi else ''}")
            g = lambda s, w: st[m][(s, w)]  # noqa: E731
            inter_p = (g("10h", "onset")[0] - g("10h", "plain")[0]) - (g("1h", "onset")[0] - g("1h", "plain")[0])
            inter_d = (g("10h", "onset")[1] - g("10h", "plain")[1]) - (g("1h", "onset")[1] - g("1h", "plain")[1])
            lo, hi = ci(inter_d)
            md += [f"| data effect (10h − 1h) | {rows[0]} | {rows[1]} | interaction: {inter_p:+.1f} [{lo:+.1f}, {hi:+.1f}]"
                   f"{'*' if not lo <= 0 <= hi else ''} |", ""]
    md += ["Interaction = (10h onset − 10h plain) − (1h onset − 1h plain): how much the onset effect changes with "
           "10× the data (equivalently, how much the data effect changes with onset weighting).", ""]
    # every behaviorally tested checkpoint of the 1h onset runs (candidates + extra steps), point estimates
    md += ["## Every tested checkpoint of the 1h runs", "",
           "Point estimates on the same 400 files. Candidates come from the selection rule (top 3 by whole-wait silence "
           "probability + final); other steps were tested afterwards as extra checkpoints (`scripts/extra_ckpts.sh`) "
           "and do not change the selected best.", "",
           "| model | overall score | " + " | ".join(r[0] for r in RATES) + " |", "|---" * (len(RATES) + 2) + "|"]
    for lr in LRS:
        for run in (f"train_1h_v2_lr{lr}", f"train_1h_v2_lr{lr}_onsetw3"):
            b = best(run)
            for f in sorted((REPO / "results/metrics").glob(f"{run}__s*.jsonl")):
                m = f.stem
                if run.endswith("lr" + lr) and m != b:
                    continue  # plain runs: their best only (the 2x2 cell)
                st, _, _ = stats({("x", "x"): m}, 200)
                cells = [f"{st['overall score'][('x', 'x')][0]:.1f}"] + [f"{st[r[0]][('x', 'x')][0]:.1f}" for r in RATES]
                md.append(f"| `{m}`{' (best)' if m == b else ''} | " + " | ".join(cells) + " |")
    md.append("")
    (REPO / "results/onset_x_size.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
